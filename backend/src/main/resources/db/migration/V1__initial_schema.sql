-- =========================================================
-- FixFlow - V1 Initial Database Schema
-- =========================================================

-- 1. USERS
-- Global user accounts. A user can belong to multiple societies.

Create TABLE users (
    id BIGINT GENERATED BY DEFAULT as IDENTITY PRIMARY KEY ,
    full_name VARCHAR(150) NOT NULL ,
    email VARCHAR(255) NOT NULL ,
    password_hash VARCHAR(255) not null ,
    phone_number VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL  DEFAULT CURRENT_TIMESTAMP
);


-- Email uniqueness is case-insensitive.
CREATE UNIQUE INDEX uq_users_email_lower
    ON users (LOWER(email));

-- 2. SOCIETIES
-- Each residential society is an independent tenant.

CREATE  TABLE societies(
    id BIGINT GENERATED by default as identity primary key ,
    name varchar(200) not null ,
    registration_number VARCHAR(100),
    address TEXT not null ,
    city VARCHAR(100) not null,
    state varchar(100) not null ,
    postal_code Varchar(15) not null ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. SOCIETY MEMBERSHIPS
-- Connects a global user to a society with a society-specific role.

CREATE table society_memberships (
    id BIGINT generated by default as identity primary key ,
    user_id BIGINT not null ,
    society_id BIGINT not null ,

    role varchar(30) not null ,
    status varchar(30) not null DEFAULT 'PENDING',

    joined_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    Constraint  fk_memberships_user
                                 FOREIGN KEY (user_id) references users(id)
                                 on delete restrict ,

    CONSTRAINT fk_memberships_society
                                 foreign key (society_id) references societies(id)
                                 on delete restrict ,


    CONSTRAINT uq_memberships_user_society
                                 unique (user_id,society_id),


    -- Required as a composite foreign-key target below.
    CONSTRAINT uq_membership_id_society
        UNIQUE (id, society_id),


    CONSTRAINT chk_membership_role
                                 CHECK ( role In ('RESIDENT' ,'SOCIETY_MANAGER' ,'TECHNICIAN')),


    CONSTRAINT chk_membership_status
                                 check ( status in ('PENDING' ,'ACTIVE' ,'REJECTED' ,'SUSPENDED'))

);
CREATE INDEX idx_memberships_society_role_status
    on society_memberships(society_id,role,status);



-- 4. BUILDINGS
-- Physical buildings within a society.

CREATE TABLE buildings (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           society_id BIGINT NOT NULL,
                           name VARCHAR(100) NOT NULL,
                           created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                           CONSTRAINT fk_buildings_society
                               FOREIGN KEY (society_id) REFERENCES societies(id)
                                   ON DELETE RESTRICT,

                           CONSTRAINT uq_building_name_per_society
                               UNIQUE (society_id, name),

    -- Required as a composite foreign-key target below.
                           CONSTRAINT uq_building_id_society
                               UNIQUE (id, society_id)
);

-- 5. APARTMENTS
-- Individual residential units within a building.
-- society_id allows the database to enforce society consistency.

CREATE TABLE apartments (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            building_id BIGINT NOT NULL,
                            society_id BIGINT NOT NULL,
                            flat_number VARCHAR(30) NOT NULL,
                            floor_number INTEGER,
                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT fk_apartments_building_society
                                FOREIGN KEY (building_id, society_id)
                                    REFERENCES buildings(id, society_id)
                                    ON DELETE RESTRICT,

                            CONSTRAINT uq_apartment_flat_per_building
                                UNIQUE (building_id, flat_number),

    -- Required as a composite foreign-key target below.
                            CONSTRAINT uq_apartment_id_society
                                UNIQUE (id, society_id)
);


-- 6. MEMBERSHIP APARTMENTS
-- Connects a society membership to one or more apartments.
-- Supports OWNER, TENANT and FAMILY_MEMBER relationships.
-- valid_until allows us to retain previous relationships.

CREATE TABLE membership_apartments (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       membership_id BIGINT NOT NULL,
                                       apartment_id BIGINT NOT NULL,
                                       society_id BIGINT NOT NULL,

                                       relationship VARCHAR(30) NOT NULL,

                                       valid_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                       valid_until TIMESTAMPTZ,

                                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                       CONSTRAINT fk_membership_apartment_membership
                                           FOREIGN KEY (membership_id, society_id)
                                               REFERENCES society_memberships(id, society_id)
                                               ON DELETE RESTRICT,

                                       CONSTRAINT fk_membership_apartment_apartment
                                           FOREIGN KEY (apartment_id, society_id)
                                               REFERENCES apartments(id, society_id)
                                               ON DELETE RESTRICT,

                                       CONSTRAINT chk_apartment_relationship
                                           CHECK (relationship IN ('OWNER', 'TENANT', 'FAMILY_MEMBER')),

                                       CONSTRAINT chk_apartment_relationship_dates
                                           CHECK (valid_until IS NULL OR valid_until > valid_from)
);

-- Prevent duplicate active relationships between the same
-- membership and apartment, while preserving historical records.
CREATE UNIQUE INDEX uq_active_membership_apartment
    ON membership_apartments (membership_id, apartment_id)
    WHERE valid_until IS NULL;

CREATE INDEX idx_membership_apartments_membership
    ON membership_apartments (membership_id);

CREATE INDEX idx_membership_apartments_apartment
    ON membership_apartments (apartment_id);




